// W27 original Pancake multi-Page ownership planner.
// Does not generate/rotate any Page token. Calls ORIGINAL official account
// GET /api/v1/pages, per-Page GET users and W24 current Page binding ports.
// Any mutation of existing token requires a distinct explicit user approval.
const fail=(code,status=403)=>{throw Object.assign(new Error(code),{code,status})};
const pid=s=>typeof s==='string'&&/^[0-9]{1,40}$/.test(s);
export function createPancakeMultiPageManager({
  listOwnedPages,verifyPageAccess,readCurrentW24PageBinding,
  bindVerifiedW24Page,revokeSpecificW24Page
}={}){
  for(const [name,fn] of Object.entries({listOwnedPages,verifyPageAccess,readCurrentW24PageBinding}))
    if(typeof fn!=='function')throw Error('W27_MISSING_ORIGINAL_'+name);
  if(bindVerifiedW24Page!==undefined&&typeof bindVerifiedW24Page!=='function')
    throw Error('W24_PAGE_BINDING_PORT_INVALID');
  if(revokeSpecificW24Page!==undefined&&typeof revokeSpecificW24Page!=='function')
    throw Error('W24_PAGE_REVOKE_PORT_INVALID');
  async function discover(){
    // Token consumed only by injected W27 original official REST, never here.
    const result=await listOwnedPages();
    if(!Array.isArray(result?.pages)||result?.canSend!==false)
      fail('W27_OFFICIAL_ACCOUNT_PAGES_UNVERIFIED',503);
    const found=new Set(),pages=[];
    for(const page of result.pages){
      const pageId=String(page?.providerPageId??page?.id??'');
      if(!pid(pageId)||found.has(pageId))continue;
      found.add(pageId);
      if(!['FACEBOOK','FB_PAGE','FACEBOOK_PAGE','facebook','facebook_page'].includes(page.platform))
        continue; // Zalo etc must not become Facebook Messenger or FB_PAGE.
      const current=await readCurrentW24PageBinding({pageId});
      if(current && (
        current.pageId!==pageId || current.channel!=='FB_PAGE' ||
        current.provider!=='PANCAKE'
      ))fail('W24_PAGE_CROSS_SCOPE_IN_DISCOVERY');
      pages.push(Object.freeze({
        pageId,name:typeof page.name==='string'?page.name.slice(0,180):null,
        channel:'FB_PAGE',
        connected:current?.status==='ACTIVE'&&current?.verified===true,
        connectionState:current?.status==='ACTIVE'&&current?.verified===true?
          'AUTHORIZED_READ_ONLY':'NEEDS_PAGE_TOKEN',
        canSend:false
      }));
    }
    return Object.freeze({status:'PAGE_CHOICES_FROM_OFFICIAL_ACCOUNT',
      pages:Object.freeze(pages),canSend:false,
      // No token is auto-generated or regenerated by discovery.
      automaticTokenGeneration:false});
  }
  async function bindSelectedPage({pageId,explicitUserSelection=false}={}){
    if(!pid(pageId)||explicitUserSelection!==true)
      fail('W27_EXPLICIT_SELECTED_PAGE_REQUIRED',422);
    if(typeof bindVerifiedW24Page!=='function')
      fail('W24_PER_PAGE_BINDING_PORT_MISSING',503);
    const discovered=await discover();
    const target=discovered.pages.find(p=>p.pageId===pageId);
    if(!target)fail('W27_PAGE_NOT_IN_CURRENT_USER_ACCOUNT',403);
    const proof=await verifyPageAccess({pageId});
    if(proof?.verified!==true||proof.pageId!==pageId||
       proof.canSend!==false||proof.source!=='PANCAKE_OFFICIAL_PAGE_API')
      fail('W27_PAGE_TOKEN_NOT_VERIFIED',403);
    const receipt=await bindVerifiedW24Page({pageId,
      verifiedPageToken:true,source:'PANCAKE_OFFICIAL_PAGE_API',
      canSend:false});
    if(receipt?.committed!==true||receipt.pageId!==pageId||
       !Number.isSafeInteger(receipt.bindingRevision)||receipt.bindingRevision<1)
      fail('W24_PER_PAGE_BINDING_NOT_COMMITTED',503);
    const current=await readCurrentW24PageBinding({pageId});
    if(current?.status!=='ACTIVE'||current.verified!==true||
       current.pageId!==pageId||current.bindingRevision!==receipt.bindingRevision)
      fail('W24_PER_PAGE_BINDING_READBACK_FAILED',409);
    return Object.freeze({pageId,status:'AUTHORIZED_READ_ONLY',
      bindingRevision:current.bindingRevision,canSend:false});
  }
  async function bindMultiplePages({pageIds,explicitUserSelection=false}={}){
    if(!Array.isArray(pageIds)||pageIds.length<1||pageIds.length>100||
       !pageIds.every(pid)||new Set(pageIds).size!==pageIds.length||
       explicitUserSelection!==true)fail('W27_MULTI_PAGE_SELECTION_INVALID',422);
    const items=[];
    // Per-page independent transaction; a failure must never magically
    // authorize others. No parallel uncontrolled token rotations.
    for(const pageId of pageIds){
      try{items.push(await bindSelectedPage({pageId,explicitUserSelection:true}));}
      catch(e){items.push(Object.freeze({pageId,status:'NOT_CONNECTED',
        error:e?.code||'PAGE_AUTHENTICATION_FAILED',canSend:false}));}
    }
    return Object.freeze({status:'PER_PAGE_RESULTS',items:Object.freeze(items),
      allConnected:items.every(i=>i.status==='AUTHORIZED_READ_ONLY'),canSend:false});
  }
  async function revokeOne({pageId,explicitUserSelection=false}={}){
    if(!pid(pageId)||!explicitUserSelection)fail('W27_EXPLICIT_PAGE_REVOKE_REQUIRED',422);
    if(typeof revokeSpecificW24Page!=='function')fail('W24_PER_PAGE_REVOKE_PORT_MISSING',503);
    const receipt=await revokeSpecificW24Page({pageId});
    if(receipt?.revoked!==true||receipt.pageId!==pageId)
      fail('W24_PER_PAGE_REVOKE_NOT_COMMITTED',503);
    const latest=await readCurrentW24PageBinding({pageId});
    if(latest?.status==='ACTIVE')fail('W24_PAGE_REVOKE_READBACK_FAILED',409);
    return Object.freeze({pageId,status:'REVOKED',canSend:false});
  }
  return Object.freeze({discover,bindSelectedPage,bindMultiplePages,revokeOne});
}
